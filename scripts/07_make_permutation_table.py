"""Step 7. LaTeX table of the permutation tests for the paper (one row per judge).

Reads the TSV written by 06_permutation_tests.py --tsv (permutation p-values) and, if present, the
TSV written by 18_equal_tau_tests.py --tsv (bootstrap z-test p-values), and writes a booktabs table:
judge, tau (published = reproduced), adjacent gap and permutation p to the next judge, and the gap,
permutation p and bootstrap z-test p against the top judge. Regenerate rather than editing by hand.

Usage: python scripts/07_make_permutation_table.py [--tsv results/g-j1/06_permutation_seed0.tsv]
           [--jack-tsv results/g-j2/18_equal_tau_tests.tsv] [--out paper/manuscript/tables/permutation.tex]
"""
import argparse
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.environ.get("PAPER_ROOT") or os.path.join(ROOT, "paper")  # where generated paper files go (README, Usage)
CAPTION = (r"Tests on the LLMJudge leaderboard (25 topics, 31 runs). $\tau$: published $\tau_b$, reproduced "
           r"exactly. $p_P$: permutation test ($P=10{,}000$); $p_B$: bootstrap $z$-test ($B=10{,}000$). All $p$ are "
           r"two-sided and uncorrected; the two $p_P$ columns come from separate runs.")


def read(tsv):
    meta, adj, top = "", {}, {}
    for line in open(tsv):
        if line.startswith("#"):
            meta = line[1:].strip()
            continue
        if line.startswith("comparison"):
            continue
        kind, a, b, ta, tb, d, p, ph = line.rstrip("\n").split("\t")
        rec = dict(a=a, b=b, ta=float(ta), tb=float(tb), d=float(d), p=float(p), ph=float(ph))
        (adj if kind == "adjacent" else top)[a if kind == "adjacent" else b] = rec
    return meta, adj, top


def read_jack(tsv):
    out = {}
    if not tsv or not os.path.exists(tsv):
        return out
    cols = None
    for line in open(tsv):
        if line.startswith("#"):
            continue
        c = line.rstrip("\n").split("\t")
        if cols is None:
            cols = c
            continue
        r = dict(zip(cols, c))
        out[(r["kind"], r["a"] if r["kind"] == "adjacent" else r["b"])] = float(r["p_boot"])
    return out


def fmt_p(p):
    return f"{p:.3f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tsv", default=os.path.join(ROOT, "results", "g-j1", "06_permutation_seed0.tsv"))
    ap.add_argument("--jack-tsv", default=os.path.join(ROOT, "results", "g-j2", "18_equal_tau_tests.tsv"))
    ap.add_argument("--out", default=os.path.join(PAPER, "manuscript", "tables", "permutation.tex"))
    args = ap.parse_args()

    meta, adj, top = read(args.tsv)
    jack = read_jack(args.jack_tsv)
    if not jack:
        raise SystemExit(f"missing bootstrap p-values: run 18_equal_tau_tests.py --tsv {args.jack_tsv}")
    first = next(iter(adj.values()))["a"]
    order = [first]
    while order[-1] in adj:
        order.append(adj[order[-1]]["b"])
    tau = {r["a"]: r["ta"] for r in adj.values()}
    tau.update({r["b"]: r["tb"] for r in adj.values()})

    lines = [
        f"% Generated by judge-significance/scripts/07_make_permutation_table.py from {os.path.basename(args.tsv)}",
        f"% ({meta}). Do not edit by hand; regenerate.",
        r"\begin{table}[t]",
        r"\caption{" + CAPTION + "}",
        r"\label{tab:permutation}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}rlrrrrrrr@{}}",
        r"\toprule",
        r" & & & \multicolumn{3}{c}{vs.\ next} & \multicolumn{3}{c}{vs.\ top judge} \\",
        r"\cmidrule(lr){4-6}\cmidrule(l){7-9}",
        r"\# & Judge & $\tau$ & $\Delta\tau$ & $p_P$ & $p_B$ & $\Delta\tau$ & $p_P$ & $p_B$ \\",
        r"\midrule",
    ]
    for i, j in enumerate(order, 1):
        nxt = (f"{adj[j]['d']:.4f} & {fmt_p(adj[j]['p'])} & {fmt_p(jack[('adjacent', j)])}" if j in adj else "-- & -- & --")
        vs = (f"{top[j]['d']:.4f} & {fmt_p(top[j]['p'])} & {fmt_p(jack[('top', j)])}" if j in top else "-- & -- & --")
        lines.append(f"{i} & {j} & {tau[j]:.4f} & {nxt} & {vs} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(order)} rows to {os.path.normpath(args.out)}")


if __name__ == "__main__":
    main()
