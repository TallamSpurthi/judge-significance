"""Step 35. LaTeX table of the bootstrap z-test's resolution on LLMJudge by number of topics (Table 2).

Reads step 32's results/g-j2/32_size_adjusted_resolution.tsv (no new simulation) and writes, for each number of
topics, the resolution at nominal alpha, with the pooled calibration on the exactly tied pairs and with every tied
pair held to 5% (each with the number of judge pairs at least that far apart), and the share of Monte Carlo
redraws in which the pooled-calibrated test resolves no gap.

Usage: python scripts/35_make_resolution_table.py [--tsv results/g-j2/32_size_adjusted_resolution.tsv]
                                                   [--out paper/manuscript/tables/resolution.tex]
"""
import argparse
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.environ.get("PAPER_ROOT") or os.path.join(ROOT, "paper")  # where generated paper files go (README, Usage)


def read_tsv(path):
    with open(path) as f:
        lines = [line for line in f if not line.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t"))


def cell(res, npairs):
    """Resolution at three decimals with its number of pairs, or 'none'."""
    if res.strip().lower() in ("none", "nan", ""):
        return "none"
    return f"{float(res):.3f} ({int(npairs)})"


def pct(x):
    """Percentage at one decimal; 100 only when every draw resolves no gap."""
    v = 100 * float(x)
    return "100" if v == 100 else f"{v:.1f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tsv", default=os.path.join(ROOT, "results", "g-j2", "32_size_adjusted_resolution.tsv"))
    ap.add_argument("--out", default=os.path.join(PAPER, "manuscript", "tables", "resolution.tex"))
    args = ap.parse_args()
    rows = read_tsv(args.tsv)
    body = []
    for r in rows:
        body.append(f"{int(r['n'])} & {cell(r['nominal_res'], r['nominal_npairs'])} & "
                    f"{cell(r['pooled_res'], r['pooled_npairs'])} & {cell(r['worst_pair_res'], r['worst_pair_npairs'])} & "
                    f"{pct(r['mc_none'])} \\\\")
    tex = "\n".join([
        "% Generated by judge-significance/scripts/35_make_resolution_table.py from results/g-j2/32_size_adjusted_resolution.tsv. Do not edit by hand; regenerate.",
        r"\begin{table}[t]",
        r"\caption{Resolution of the bootstrap $z$-test on LLMJudge by number of topics, drawn with replacement from"
        r" the 25 (200 samples per pair): the smallest gap $g$ such that 80\% of the judge pairs at least $g$ apart"
        r" reach 80\% power, with the number of such pairs in parentheses; none: no gap qualifies. Nominal:"
        r" $\alpha=0.05$. Pooled: calibrated so that the exactly tied pairs together reject 5\%. Per pair: so that"
        r" no tied pair rejects more than 5\%. None (\%): share of Monte Carlo redraws of each pair's power in which"
        r" the pooled test resolves no gap.}",
        r"\label{tab:resolution}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}rlllr@{}}",
        r"\toprule",
        r"Topics & Nominal & Pooled & Per pair & None (\%) \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(tex)
    print(f"wrote {os.path.basename(args.out)}")  # no directories: logs carry no local paths


if __name__ == "__main__":
    main()
