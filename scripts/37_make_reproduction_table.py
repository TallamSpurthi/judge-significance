"""Step 37. LaTeX table of the LLMJudge Table 3 reproduction, judge by judge (AILET appendix).

Reads step 4's results/g-j1/04_table3_comparison.log (no new computation) and writes, for each of the 33 public
judges in order of published tau, the published Kendall tau, our tau_b with the inferred 31-run set (raw labels), and
our tau_b with all 35 runs. The caption's counts are computed from the same rows. Standard library only.

Usage: python scripts/37_make_reproduction_table.py [--log results/g-j1/04_table3_comparison.log]
                                                    [--out paper/venues/acm-ai-letters/tables/reproduction.tex]
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.environ.get("PAPER_ROOT") or os.path.join(ROOT, "paper")  # where generated paper files go (README, Usage)
ROW = re.compile(r"^\s+(\S+)\s+(\d\.\d{4})\s+(\d\.\d{4})\s+(\d\.\d{4})\s+(\d\.\d{4})\s+[+-]\d\.\d{4}\s+(\d\.\d{4})\s+\|")


def read_blocks(path):
    """{block header: [(judge, tau_pub, tau_raw)]} for the '== 31 runs' and '== all 35 runs' blocks."""
    blocks, cur = {}, None
    with open(path) as f:
        for line in f:
            if line.startswith("== "):
                cur = "31" if line.startswith("== 31 runs") else "35" if line.startswith("== all 35 runs") else None
                if cur:
                    blocks[cur] = []
                continue
            m = ROW.match(line)
            if cur and m:
                blocks[cur].append((m.group(1), m.group(2), m.group(3)))
    return blocks


def tex_name(s):
    return s.replace("_", r"\_")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--log", default=os.path.join(ROOT, "results", "g-j1", "04_table3_comparison.log"))
    ap.add_argument("--out", default=os.path.join(PAPER, "venues", "acm-ai-letters", "tables", "reproduction.tex"))
    args = ap.parse_args()
    b = read_blocks(args.log)
    r31, r35 = b["31"], {j: raw for j, _, raw in b["35"]}
    assert len(r31) == 33 and len(r35) == 33, (len(r31), len(r35))
    exact31 = sum(pub == raw for _, pub, raw in r31)
    exact35 = sum(pub == r35[j] for j, pub, _ in r31)
    within35 = sum(abs(float(pub) - float(r35[j])) < 0.01 for j, pub, _ in r31)
    maxdiff35 = max(abs(float(pub) - float(r35[j])) for j, pub, _ in r31)
    rows = [f"{tex_name(j)} & {pub} & {raw} & {r35[j]}" for j, pub, raw in r31]
    half = (len(rows) + 1) // 2
    left, right = rows[:half], rows[half:] + [" & & & "] * (2 * half - len(rows))
    body = [f"{a} & {c} \\\\" for a, c in zip(left, right)]
    tex = "\n".join([
        "% Generated by judge-significance/scripts/37_make_reproduction_table.py from results/g-j1/04_table3_comparison.log."
        " Do not edit by hand; regenerate.",
        r"\begin{table}[!h]",
        r"\caption{The 33 public LLMJudge judges in order of published $\tau$: published Kendall's $\tau$ (Pub.), our $\tau_b$"
        r" with the inferred set of 31 runs (31), and with all 35 runs (35), each over the 25 test topics with nDCG@10"
        f" and the labels as submitted. The 31-run set matches {exact31} of the 33 published values to four decimals;"
        f" all 35 runs match {exact35}, are within 0.01 for {within35}, and differ by up to {maxdiff35:.4f}.}}",
        r"\label{tab:reproduction}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}lrrr@{\hspace{10pt}}lrrr@{}}",
        r"\toprule",
        r"Judge & Pub. & 31 & 35 & Judge & Pub. & 31 & 35 \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(tex)
    print(f"wrote {os.path.basename(args.out)}: 31-run exact {exact31}/33; 35-run exact {exact35}/33,"
          f" within 0.01 {within35}/33, max diff {maxdiff35:.4f}")  # no directories: logs carry no local paths


if __name__ == "__main__":
    main()
