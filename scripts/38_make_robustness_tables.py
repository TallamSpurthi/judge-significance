"""Step 38. LaTeX tables and macros for the robustness checks of step 34 (AILET appendix).

Reads results/g-j3/34_robustness_checks.log, 19_dl_benchmark.log and 24_extrapolation.tsv (no new simulation) and writes:
  tables/robustness-criterion.tex    nominal-alpha resolution of the bootstrap z-test under four criteria (section D)
  tables/robustness-calibration.tex  calibration transfer with one group of tied pairs left out (section B)
  robustness-numbers.tex             macros for the held-out reversals pair by pair (section A), for the re-parsed DL 2019
                                     labels (step 19) and for the resolution predicted from 25-topic subsets (step 24)
Standard library only.

Usage: python scripts/38_make_robustness_tables.py [--log results/g-j3/34_robustness_checks.log]
                                                   [--outdir paper/venues/acm-ai-letters]
"""
import argparse
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.environ.get("PAPER_ROOT") or os.path.join(ROOT, "paper")  # where generated paper files go (README, Usage)


def section(text, letter):
    m = re.search(rf"(?ms)^{letter}\. .*?(?=^[A-Z]\. |\Z)", text)
    assert m, letter
    return m.group(0)


def res_cell(s):
    """'0.116 (11 pairs)' -> '0.116 (11)'; 'none' -> 'none'."""
    s = s.strip()
    if s == "none":
        return "none"
    m = re.fullmatch(r"(\d\.\d{3}) \((\d+) pairs\)", s)
    assert m, s
    return f"{m.group(1)} ({m.group(2)})"


def criterion_table(sec_d):
    rows = []
    for line in sec_d.splitlines():
        m = re.match(r"\s+(\d+)% of pairs at (\d+)% power: 200 topics (.+?); 400 topics (.+)$", line)
        if m:
            share, power, r200, r400 = m.groups()
            mark = r"\textsuperscript{*}" if (share, power) == ("80", "80") else ""
            rows.append(f"{share}\\% & {power}\\%{mark} & {res_cell(r200)} & {res_cell(r400)} \\\\")
    assert len(rows) == 4, rows
    n = re.search(r"bootstrap z-test, (\d+) pairs", sec_d).group(1)
    return "\n".join([
        "% Generated by judge-significance/scripts/38_make_robustness_tables.py from results/g-j3/34_robustness_checks.log."
        " Do not edit by hand; regenerate.",
        r"\begin{table}[!h]",
        r"\caption{Resolution of the bootstrap $z$-test at nominal $\alpha=0.05$ under four criteria: the smallest gap"
        r" $g$ such that the given share of judge pairs at least $g$ apart reach the given power, with the number of"
        f" such pairs in parentheses; none: no gap qualifies. Same simulated powers as Table~\\ref{{tab:resolution}}"
        f" ({n} pairs, 200 samples per pair and size). *The paper's criterion.}}",
        r"\label{tab:robust-criterion}",
        r"\small",
        r"\begin{tabular}{@{}rrll@{}}",
        r"\toprule",
        r"Share of pairs & Power & 200 topics & 400 topics \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])


def calibration_table(sec_b):
    head = re.search(r"\((\d+) pairs, (\d+) tied pairs in (\d+) groups, (\d+) replicates", sec_b)
    npairs, ntied, ngroups, reps = head.groups()
    cells, order = {}, []
    for line in sec_b.splitlines():
        m = re.match(r"\s+(\d\.\d{4}) \((\d+)\) \|\s+(\d+) \| [\d.]+ \| (\d\.\d{4}) \| [\d.]+ \| (\d\.\d{4}) ", line)
        if m:
            g, k, t, pooled, worst = m.groups()
            if (g, k) not in order:
                order.append((g, k))
            cells[(g, k, t)] = f"{float(pooled):.3f} ({float(worst):.3f})"
    res = {}
    for line in sec_b.splitlines():
        m = re.match(r"\s+held out (\d\.\d{4}), (\d+) topics: cutoff [\d.]+, resolution (.+)$", line)
        if m:
            res[(m.group(1), m.group(2))] = res_cell(m.group(3))
    assert len(order) == int(ngroups), order
    topics = ["25", "100", "200", "400"]
    rows = [f"{g} ({k}) & " + " & ".join(cells[(g, k, t)] for t in topics)
            + f" & {res[(g, '200')]} & {res[(g, '400')]} \\\\" for g, k in order]
    return "\n".join([
        "% Generated by judge-significance/scripts/38_make_robustness_tables.py from results/g-j3/34_robustness_checks.log."
        " Do not edit by hand; regenerate.",
        r"\begin{table}[!h]",
        f"\\caption{{Calibration transfer. The {ntied} exactly tied judge pairs fall into {ngroups} groups by their"
        r" shared $\tau$ (pairs in parentheses). For each group, the per-pair cutoff of Table~\ref{tab:resolution} is"
        r" fitted on the other groups and applied to the held-out group: rejection rate of the held-out group's pairs"
        r" together, with its worst pair in parentheses ($\alpha$ target 0.05; " + reps + r" samples per pair and size),"
        f" and the resolution when that cutoff is applied to all {npairs} pairs (number of pairs at least that far"
        r" apart in parentheses).}",
        r"\label{tab:robust-calibration}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}lllllll@{}}",
        r"\toprule",
        r"Held-out $\tau$ (pairs) & 25 topics & 100 & 200 & 400 & Resol., 200 & 400 \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])


def reversal_macros(sec_a):
    def num(pat):
        m = re.search(pat, sec_a)
        assert m, pat
        return m.group(1)
    vals = {
        "rbRevLLMJudge": num(r"reversed, 25 topics with LLMJudge labels vs held-out: (\d+)"),
        "rbRevNIST": num(r"reversed, 25 topics with all NIST labels vs held-out: (\d+)"),
        "rbRevGone": num(r"no longer reversed: (\d+)"),
        "rbRevNew": num(r"newly reversed:\s+(\d+)"),
        "rbRevBoth": num(r"reversed under both: (\d+)"),
    }
    assert int(vals["rbRevBoth"]) + int(vals["rbRevGone"]) == int(vals["rbRevLLMJudge"])
    assert int(vals["rbRevBoth"]) + int(vals["rbRevNew"]) == int(vals["rbRevNIST"])
    lines = ["% Generated by judge-significance/scripts/38_make_robustness_tables.py from results/g-j3/34_robustness_checks.log"
             " (section A). Do not edit by hand; regenerate."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vals.items()]
    return "\n".join(lines) + "\n"


def macro_lines(source, vals):
    return [f"% Generated by judge-significance/scripts/38_make_robustness_tables.py from {source}."
            " Do not edit by hand; regenerate."] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vals.items()]


def reparse_macros(text):
    """tau of llama-3.3-70b/umbrela on DL 2019 with the labels as released and re-parsed, and the published value (section 1b)."""
    block = re.search(r"(?ms)^=+ dl19: .*?(?=^=+ dl20: )", text).group(0)

    def row(name):
        m = re.search(rf"(?m)^  {re.escape(name)} .*\| *(\d\.\d+) +(\d\.\d+) +[+-]", block)
        assert m, name
        return float(m.group(1)), float(m.group(2))

    (rel, pub), (rep, pub2) = row("llama-3.3-70b/umbrela"), row("70B re-parsed (sensitivity)")
    assert pub == pub2, (pub, pub2)
    return {"rbReparseRel": f"{rel:.3f}", "rbReparseNew": f"{rep:.3f}", "rbReparsePub": f"{pub:.3f}"}


def prediction_macros(path):
    """Bootstrap-test resolution predicted from 25-topic subsets against the one measured on all topics (step 24)."""
    with open(path) as f:
        head = f.readline()
        data = list(csv.DictReader(f, delimiter="\t"))
    rows = {(r["year"], int(r["n"])): r for r in data if r["part"] == "extrapolation"}
    subsets = int(re.search(r"K=(\d+)", head).group(1))
    vals = {}
    for n, name in ((54, "Full"), (100, "Hundred")):
        r = rows["dl20", n]
        assert int(r["res_pred_none"]) == 0, r  # the median is over every subset
        for k, c in (("Meas", "res_measured"), ("Med", "res_pred_median"), ("Min", "res_pred_min"), ("Max", "res_pred_max")):
            vals[f"rbRes{k}{name}"] = f"{float(r[c]):.2f}"
    r = rows["dl19", 100]
    vals["rbResNineteenMeas"] = f"{float(r['res_measured']):.2f}"
    vals["rbResNineteenNone"] = r["res_pred_none"]
    vals["rbResSubsets"] = str(subsets)
    sys31 = next(r for r in data if r["part"] == "systems" and r["year"] == "dl20" and r["n"] == "100")
    assert int(sys31["res_pred_none"]) == 0, sys31  # every random draw of 31 systems resolves a gap
    vals["rbSysMin"], vals["rbSysMax"] = (f"{float(sys31[c]):.2f}" for c in ("res_pred_min", "res_pred_max"))
    return vals


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--log", default=os.path.join(ROOT, "results", "g-j3", "34_robustness_checks.log"))
    ap.add_argument("--dl-log", default=os.path.join(ROOT, "results", "g-j3", "19_dl_benchmark.log"))
    ap.add_argument("--extrapolation", default=os.path.join(ROOT, "results", "g-j3", "24_extrapolation.tsv"))
    ap.add_argument("--outdir", default=os.path.join(PAPER, "venues", "acm-ai-letters"))
    args = ap.parse_args()
    text = open(args.log).read()
    out = {
        os.path.join("tables", "robustness-criterion.tex"): criterion_table(section(text, "D")),
        os.path.join("tables", "robustness-calibration.tex"): calibration_table(section(text, "B")),
        "robustness-numbers.tex": reversal_macros(section(text, "A")) + "\n".join(
            macro_lines("results/g-j3/19_dl_benchmark.log (section 1b)", reparse_macros(open(args.dl_log).read()))
            + macro_lines("results/g-j3/24_extrapolation.tsv", prediction_macros(args.extrapolation))) + "\n",
    }
    for rel, tex in out.items():
        path = os.path.join(args.outdir, rel)
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w") as f:
            f.write(tex)
        print(f"wrote {rel}")  # relative names only: logs carry no local paths


if __name__ == "__main__":
    main()
