"""Step 40. Two LaTeX tables for the ACM AI Letters appendix, from released results (no new simulation):

  tables/adjacent-tests.tex    the 32 adjacent pairs of the published LLMJudge order: gap in tau, two-sided
                               permutation p and bootstrap z-test p, uncorrected (results/g-j2/18_equal_tau_tests.tsv;
                               every permutation p checked against results/g-j1/06_permutation_seed0.tsv)
  tables/test-comparison.tex   the permutation, studentized permutation and bootstrap z-tests on the same samples
                               (results/g-j2/23_test_size_check.tsv and 23_test_size_check_adjusted.tsv): rejection
                               rate for the exactly tied pairs, power for pairs at least 0.10 apart, at nominal alpha
                               and calibrated, at 25 and 100 topics

Before writing, the script checks the numbers the paper states about these data against the macros in
numbers.tex (--numbers; step 13 writes it), and refuses to write if any differs. Without that file it writes the
tables and says that this check was skipped; the checks of one result file against another always run. Standard
library only.

Usage: python scripts/40_make_test_tables.py [--outdir paper/venues/acm-ai-letters] [--numbers paper/manuscript/numbers.tex]
"""
import argparse
import csv
import os
import re
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.environ.get("PAPER_ROOT") or os.path.join(ROOT, "paper")  # where generated paper files go (README, Usage)
HEAD = ("% Generated by judge-significance/scripts/40_make_test_tables.py from {src}. Do not edit by hand; regenerate.")


def read_tsv(path):
    with open(path) as f:
        return list(csv.DictReader([line for line in f if not line.startswith("#")], delimiter="\t"))


def macros(path):
    """The macros of numbers.tex, or None if step 13 has not written it (a fresh clone)."""
    if not os.path.exists(path):
        print(f"no {os.path.basename(path)}: the paper's macros were not checked (run scripts/13_make_numbers.py first)")
        return None
    with open(path) as f:
        return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", f.read()))


def adjacent_table(M):
    rows = [r for r in read_tsv(os.path.join(ROOT, "results", "g-j2", "18_equal_tau_tests.tsv")) if r["kind"] == "adjacent"]
    assert len(rows) == 32, len(rows)
    for r, s in zip(rows, rows[1:]):
        assert r["b"] == s["a"], (r["b"], s["a"])  # one chain down the published order
    perm06 = {(r["judge_a"], r["judge_b"]): float(r["p"])
              for r in read_tsv(os.path.join(ROOT, "results", "g-j1", "06_permutation_seed0.tsv")) if r["comparison"] == "adjacent"}
    for r in rows:
        assert abs(float(r["p_perm"]) - perm06[(r["a"], r["b"])]) < 5e-7, r
    gap = [float(r["delta"]) for r in rows]
    pp = [float(r["p_perm"]) for r in rows]
    pb = [float(r["p_boot"]) for r in rows]
    nz = [i for i, g in enumerate(gap) if g > 0]
    # the paper's statements about these pairs
    if M is not None:
        assert len(rows) - len(nz) == int(M["nAdjZeroGaps"]) and len(nz) == int(M["nAdjNonTied"])
        assert f"{max(gap):.4f}" == M["maxAdjGap"], (max(gap), M["maxAdjGap"])
        assert f"{min(pp[i] for i in nz):.3f}" == M["minAdjP"], (min(pp[i] for i in nz), M["minAdjP"])
        assert f"{min(pb[i] for i in nz):.2f}" == M["minAdjPBootNonzero"], (min(pb[i] for i in nz), M["minAdjPBootNonzero"])
    assert all(g >= 0 for g in gap) and min(pp + pb) >= 0.05
    assert all(pp[i] == pb[i] == 1 for i in range(len(rows)) if i not in nz)  # the caption: a gap of 0 gives p = 1
    cells = [f"{i + 1}--{i + 2} & {r['b']} & {g:.4f} & {p1:.3f} & {p2:.3f}"
             for i, (r, g, p1, p2) in enumerate(zip(rows, gap, pp, pb))]
    half = 16
    body = [f"{a} & {b} \\\\" for a, b in zip(cells[:half], cells[half:])]
    print(f"adjacent-tests: 32 pairs, {len(nz)} nonzero gaps; smallest p among them {min(pp[i] for i in nz):.3f} "
          f"(permutation) and {min(pb[i] for i in nz):.3f} (bootstrap); none below 0.05")
    return "\n".join([
        HEAD.format(src="results/g-j2/18_equal_tau_tests.tsv (permutation p checked against results/g-j1/06_permutation_seed0.tsv)"),
        r"\begin{table}[!h]",
        r"\caption{The 32 adjacent pairs of the published LLMJudge order (ranks as in Table~\ref{tab:reproduction}; the"
        r" upper judge of each pair is the lower judge of the pair before it, and the top judge is " + rows[0]["a"] + r"):"
        r" gap in $\tau$, and two-sided $p$ of the permutation test (P) and the bootstrap $z$-test (B), uncorrected,"
        r" over the 25 topics with the 31 systems fixed ($P=R=10{,}000$). A gap of 0 gives $p=1$.}",
        r"\label{tab:adjacent}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}llrrr@{\hspace{10pt}}llrrr@{}}",
        r"\toprule",
        r"Ranks & Lower judge & Gap & $p$ (P) & $p$ (B) & Ranks & Lower judge & Gap & $p$ (P) & $p$ (B) \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])


TESTS = [("permutation", "Permutation", "interchangeable"),
         ("studentized_permutation", "Studentized permutation", r"equal $\tau$\textsuperscript{a}"),
         ("bootstrap_z", r"Bootstrap $z$", r"equal $\tau$")]


def comparison_table(M):
    rows = read_tsv(os.path.join(ROOT, "results", "g-j2", "23_test_size_check.tsv"))
    adj = {(int(r["n"]), r["test"]): float(r["median_power"])
           for r in read_tsv(os.path.join(ROOT, "results", "g-j2", "23_test_size_check_adjusted.tsv"))}
    with open(os.path.join(ROOT, "results", "g-j2", "23_test_size_check.tsv")) as f:
        head = f.readline()
    reps, perms, boot = (int(re.search(rf"{k}=(\d+)", head).group(1)) for k in ("reps", "perms", "boot"))

    def header(name, key):  # settings of the separate step 16 runs, from their header lines
        with open(os.path.join(ROOT, "results", "g-j2", name)) as f:
            return int(re.search(rf"{key}=(\d+)", f.readline()).group(1))

    p16, r16 = header("16_real_judge_power.tsv", "perms"), header("16_real_judge_power_bootstrap.tsv", "boot")

    def rates(group, n, test):
        v = [float(r[test]) for r in rows if r["group"] == group and int(r["n"]) == n]
        return v

    tied = {(n, t): rates("exact_tie", n, t) for n in (25, 100) for t, _, _ in TESTS}
    big = {(n, t): rates("gap_ge_0.10", n, t) for n in (25, 100) for t, _, _ in TESTS}
    ntied, nbig = len(tied[(25, "permutation")]), len(big[(25, "permutation")])
    if M is not None:
        assert ntied == int(M["realExactPairsBoot"]) and nbig == int(M["realBigPairsLowBoot"]), (ntied, nbig)
    # the paper's statements from this simulation
    checks = {"studPermTieTwentyFive": statistics.median(tied[(25, "studentized_permutation")]),
              "studPermTieHundred": statistics.median(tied[(100, "studentized_permutation")]),
              "permAdjPowHundred": adj[(100, "permutation")],
              "studPermAdjPowHundred": adj[(100, "studentized_permutation")],
              "bootZAdjPowHundred": adj[(100, "bootstrap_z")]}
    for k, v in checks.items() if M is not None else ():
        assert f"{v + 1e-9:.2f}" == M[k], (k, v, M[k])
    out = []
    for t, name, null in TESTS:
        c = [name, null]
        for n in (25, 100):
            v = tied[(n, t)]
            c.append(f"{statistics.median(v):.3f} ({max(v):.3f})")
        for n in (25, 100):
            c.append(f"{statistics.median(big[(n, t)]):.3f}")
        for n in (25, 100):
            c.append(f"{adj[(n, t)]:.3f}")
        out.append(" & ".join(c) + r" \\")
    print(f"test-comparison: {ntied} tied pairs, {nbig} pairs >= 0.10 apart, {reps} samples per pair and size"
          + ("; paper macros " + ", ".join(checks) + " match" if M is not None else ""))
    return "\n".join([
        HEAD.format(src="results/g-j2/23_test_size_check.tsv and 23_test_size_check_adjusted.tsv"),
        r"\begin{table}[!h]",
        r"\caption{The three tests on the same samples: topics drawn with replacement from the 25 LLMJudge topics"
        f" ({reps} samples per pair and size; $P={perms}$, $R={boot}$; $\\alpha=0.05$). Tied: rejection rate for the"
        f" {ntied} pairs with exactly equal $\\tau$, median (worst pair). Power: median rejection rate for the {nbig}"
        r" pairs at least 0.10 apart, at nominal $\alpha$ and with each test calibrated so that the tied pairs"
        r" together reject 5\% of samples. Section~\ref{sec:res-power}'s studentized rates and calibrated powers come from"
        r" this simulation; its other rejection rates come from the separate one behind Figure~\ref{fig:power}"
        f" ($P={p16}$, $R={r16}$), so they can differ from the values here."
        r" \textsuperscript{a}Asymptotically, for smooth statistics; Kendall's $\tau$ is not one"
        r" (Section~\ref{sec:method}).}",
        r"\label{tab:tests}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}llllllll@{}}",
        r"\toprule",
        r" & & \multicolumn{2}{l}{Tied, nominal $\alpha$} & \multicolumn{2}{l}{Power, nominal} & \multicolumn{2}{l}{Power, calibrated} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(l){7-8}",
        r"Test & Null hypothesis & 25 topics & 100 & 25 & 100 & 25 & 100 \\",
        r"\midrule",
        *out,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--outdir", default=os.path.join(PAPER, "venues", "acm-ai-letters"))
    ap.add_argument("--numbers", default=os.path.join(PAPER, "manuscript", "numbers.tex"))
    args = ap.parse_args()
    M = macros(args.numbers)
    out = {os.path.join("tables", "adjacent-tests.tex"): adjacent_table(M),
           os.path.join("tables", "test-comparison.tex"): comparison_table(M)}
    for rel, tex in out.items():
        path = os.path.join(args.outdir, rel)
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w") as f:
            f.write(tex)
        print(f"wrote {rel}")


if __name__ == "__main__":
    main()
